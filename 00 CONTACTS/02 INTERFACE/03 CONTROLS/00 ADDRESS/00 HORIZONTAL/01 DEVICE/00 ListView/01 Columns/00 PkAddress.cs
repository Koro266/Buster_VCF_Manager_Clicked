//___________________________________________________________________________________________________________________________________________________
//LOCAL
using DEVICE_ROW	= CONTACTS.LOCAL.TERTIARY.DEVICE.Row;

//___________________________________________________________________________________________________________________________________________________
namespace CONTACTS.INTERFACE.CONTROLS.HORIZONTAL.LISTVIEW
{
	//___________________________________________________________________________________________________________________________________________
	public class Col0_PkDevice
	{
		private DEVICE_ROW _Device;

		//___________________________________________________________________________________________________________________________________________
		public Col0_PkDevice( DEVICE_ROW device_row )
		{
			DeviceRow = device_row;
		}
		//___________________________________________________________________________________________________________________________________________
		public string ColumnValue
		{
			get { return DeviceRow.PkDevice.AsString; }
		}
		//___________________________________________________________________________________________________________________________________
		/// <summary>
		/// Gets/sets Device row.
		/// </summary>
		private DEVICE_ROW DeviceRow
		{
			get { return _Device; }
			set { _Device = value; }
		}
	}
}
